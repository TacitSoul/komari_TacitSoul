const TABLES: Record<string, Table> = { en: EN, "zh-Hant": ZH_HANT };

/** A translation may hold "one|other" forms; the first numeric argument picks one (English plurals). */
function pickPlural(translated: string, args: readonly unknown[]): string {
  if (!translated.includes("|")) return translated;
  const [one, other = one] = translated.split("|");
  const count = args.find((arg): arg is number => typeof arg === "number");
  return count === 1 ? one : other;
}

function fill(template: string, args: readonly unknown[]): string {
  return args.length === 0 ? template : template.replace(/\{(\d+)\}/g, (match, index: string) => {
    const value = args[Number(index)];
    return value === undefined ? match : String(value);
  });
}

/** Translate a zh-Hans source string of the matrix code into the current UI language. */
export function tsText(source: string, ...args: unknown[]): string {
  const language = i18n.resolvedLanguage ?? i18n.language ?? "zh-Hans";
  const table = TABLES[language.startsWith("zh-Hant") ? "zh-Hant" : language.startsWith("zh") ? "zh-Hans" : "en"];
  const translated = table?.[source];
  return fill(translated === undefined ? source : pickPlural(translated, args), args);
}

